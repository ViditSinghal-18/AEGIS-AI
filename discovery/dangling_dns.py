@dataclass
class DanglingDnsResult:
    """Evidence-grounded evaluation of subdomain takeover risk."""

    subdomain: str
    cname_target: Optional[str]
    provider_name: Optional[str]
    is_vulnerable: bool
    status_code: Optional[int]
    fingerprint_matched: Optional[str]
    evidence: str
    remediation: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


