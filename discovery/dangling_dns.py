def resolve_cname(domain: str) -> Optional[str]:
    """Resolve DNS CNAME record using nslookup."""
    try:
        proc = subprocess.run(
            ["nslookup", "-type=CNAME", domain],
            capture_output=True,
            text=True,
            timeout=4,
        )
        for line in proc.stdout.splitlines():
            line_s = line.strip()
            if "canonical name =" in line_s:
                parts = line_s.split("canonical name =", 1)
                return parts[1].strip().rstrip(".")
    except Exception:
        pass
    return None


def verify_dangling_dns(
    subdomain: str,
    cname_target: Optional[str] = None,
    mock_response_body: Optional[str] = None,
    mock_status_code: Optional[int] = None,
) -> DanglingDnsResult:
    """Verify if a subdomain CNAME points to an unclaimed third-party cloud service.

    Requires an exact response-body fingerprint match before asserting vulnerability.
    """
    clean_sub = subdomain.strip().lower()
    target_cname = (cname_target or resolve_cname(clean_sub) or "").strip().lower()

    if not target_cname:
        return DanglingDnsResult(
            subdomain=clean_sub,
            cname_target=None,
            provider_name=None,
            is_vulnerable=False,
            status_code=None,
            fingerprint_matched=None,
            evidence="No CNAME record discovered for subdomain.",
            remediation="None required.",
        )

    # 1. Match CNAME against cloud provider fingerprint patterns
    matched_provider = None
    for prov in PROVIDER_FINGERPRINTS:
        if prov["cname_pattern"].search(target_cname):
            matched_provider = prov
            break

    if not matched_provider:
        return DanglingDnsResult(
            subdomain=clean_sub,
            cname_target=target_cname,
            provider_name=None,
            is_vulnerable=False,
            status_code=None,
            fingerprint_matched=None,
            evidence=f"CNAME points to '{target_cname}' (not a cataloged vulnerable cloud provider pattern).",
            remediation="None required.",
        )

    # 2. Strict evidence check: fetch response body and verify exact fingerprint
    resp_body = mock_response_body
    resp_status = mock_status_code

    if resp_body is None:
        try:
            # Safe HTTP fetch through SSRF-guarded fetcher
            resp = safe_fetch(f"https://{clean_sub}", timeout=4.0)
            resp_body = resp.text
            resp_status = resp.status_code
        except SafeFetchError:
            # If HTTPS fails, try HTTP
            try:
                resp = safe_fetch(f"http://{clean_sub}", timeout=4.0)
                resp_body = resp.text
                resp_status = resp.status_code
            except Exception:
                resp_body = ""
                resp_status = 0
        except Exception:
            resp_body = ""
            resp_status = 0

    body_clean = resp_body or ""
    matched_fp = None
    for fp in matched_provider["body_fingerprints"]:
        if fp.lower() in body_clean.lower():
            matched_fp = fp
            break

    if matched_fp and (resp_status in matched_provider["status_codes"] or resp_status == 404):
        return DanglingDnsResult(
            subdomain=clean_sub,
            cname_target=target_cname,
            provider_name=matched_provider["provider"],
            is_vulnerable=True,
            status_code=resp_status,
            fingerprint_matched=matched_fp,
            evidence=(
                f"Dangling CNAME confirmed: '{clean_sub}' points to '{target_cname}' ({matched_provider['provider']}). "
                f"HTTP response returned code {resp_status} matching unclaimed fingerprint: '{matched_fp}'."
            ),
            remediation=matched_provider["remediation"],
        )

    return DanglingDnsResult(
        subdomain=clean_sub,
        cname_target=target_cname,
        provider_name=matched_provider["provider"],
        is_vulnerable=False,
        status_code=resp_status,
        fingerprint_matched=None,
        evidence=(
            f"CNAME points to {matched_provider['provider']} ('{target_cname}'), "
            f"but service responds with active content (no unallocated error fingerprint found)."
        ),
        remediation="Ensure the cloud service binding is monitored and retained.",
    )


def audit_subdomain_takeovers(subdomains: List[str]) -> List[DanglingDnsResult]:
    """Audit an array of subdomains (e.g. from Certificate Transparency logs) for dangling DNS."""
    results: List[DanglingDnsResult] = []
    for sub in subdomains:
        res = verify_dangling_dns(sub)
        results.append(res)
    return results
